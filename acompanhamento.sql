('Creme de avelã', true),('Morango', true),('Creme de morango', true),('Creme de cookies', true),
('Nutella', true),('Creme de Chocolate Branco', true)
on conflict (nome) do nothing;

alter table public.acompanhamentos_disponibilidade enable row level security;

drop policy if exists "public pode ler disponibilidade" on public.acompanhamentos_disponibilidade;
create policy "public pode ler disponibilidade" on public.acompanhamentos_disponibilidade
for select to anon, authenticated using (true);

drop policy if exists "autenticado pode alterar disponibilidade" on public.acompanhamentos_disponibilidade;
create policy "autenticado pode alterar disponibilidade" on public.acompanhamentos_disponibilidade
for update to authenticated using (true) with check (true);


